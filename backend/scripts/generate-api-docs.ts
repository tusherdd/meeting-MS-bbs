/**
 * npm run docs:api → docs/API.md, generated from docs/openapi.json (run openapi:export first),
 * so the endpoint list always matches the real code.
 * Access comes from the `x-access` extension written by @Public() / @Roles():
 *   🔓 public · 👤 any logged-in user · 🛡 ADMIN or SUPER_ADMIN.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

interface Schema {
  $ref?: string;
  type?: string;
  properties?: Record<string, Schema>;
  required?: string[];
  allOf?: Schema[];
  items?: Schema;
}
interface Parameter {
  name: string;
  in: string;
  required?: boolean;
}
interface Operation {
  summary?: string;
  tags?: string[];
  parameters?: Parameter[];
  requestBody?: { content: Record<string, { schema: Schema }> };
  responses: Record<string, unknown>;
  security?: unknown[];
  'x-access'?: string;
}
interface OpenApi {
  info: { title: string; version: string };
  paths: Record<string, Record<string, Operation>>;
  components: { schemas: Record<string, Schema> };
}

/** Same grouping as SPEC.md §8. */
const TAG_ORDER = [
  'Health',
  'Auth',
  'Profile',
  'Users',
  'Designations',
  'Wings',
  'Change requests (admin)',
  'Meetings',
  'Conflicts',
  'Notifications',
  'Reports',
  'Admin',
  'Admin — email outbox',
  'Admin — audit log',
];
const METHOD_ORDER = ['get', 'post', 'patch', 'put', 'delete'];

const root = join(__dirname, '..', '..', 'docs');
const api = JSON.parse(readFileSync(join(root, 'openapi.json'), 'utf8')) as OpenApi;

function resolve(schema: Schema | undefined): Schema | undefined {
  if (!schema) return undefined;
  if (schema.$ref) return resolve(api.components.schemas[schema.$ref.split('/').pop()!]);
  if (schema.allOf) {
    const parts = schema.allOf.map(resolve).filter((s): s is Schema => Boolean(s));
    return {
      properties: Object.assign({}, ...parts.map((p) => p.properties ?? {})) as Record<string, Schema>,
      required: parts.flatMap((p) => p.required ?? []),
    };
  }
  return schema;
}

function access(op: Operation): string {
  const a = op['x-access'];
  if (a === 'public') return '🔓';
  if (a) return '🛡';
  return op.security ? '👤' : '🔓';
}

function requestFields(op: Operation): string {
  const fields: string[] = [];
  for (const p of op.parameters ?? []) {
    if (p.in === 'path') continue;
    fields.push(`\`${p.name}\`${p.required ? '*' : ''} (query)`);
  }
  const content = op.requestBody?.content;
  if (content) {
    const [type, { schema }] = Object.entries(content)[0];
    const s = resolve(schema);
    const required = new Set(s?.required ?? []);
    const names = Object.keys(s?.properties ?? {}).map((n) => `\`${n}\`${required.has(n) ? '*' : ''}`);
    if (type === 'multipart/form-data') names.push('(multipart)');
    fields.push(...names);
  }
  return fields.length ? fields.join(', ') : '—';
}

const groups = new Map<string, string[]>();
let count = 0;
for (const [path, ops] of Object.entries(api.paths)) {
  for (const method of METHOD_ORDER) {
    const op = ops[method];
    if (!op) continue;
    count++;
    const tag = op.tags?.[0] ?? 'Other';
    const shortPath = path.replace(/^\/api\/v1/, '').replace(/\{(\w+)\}/g, ':$1');
    const codes = Object.keys(op.responses).sort().join(', ');
    const row = `| ${method.toUpperCase()} | \`${shortPath}\` | ${access(op)} | ${(op.summary ?? '').replace(/\|/g, '\\|')} | ${requestFields(op)} | ${codes} |`;
    groups.set(tag, [...(groups.get(tag) ?? []), row]);
  }
}

const tags = [...TAG_ORDER.filter((t) => groups.has(t)), ...[...groups.keys()].filter((t) => !TAG_ORDER.includes(t))];
const lines = [
  '# API reference — BBS Meeting Schedule System',
  '',
  '> Generated by `npm run docs:api` from `docs/openapi.json` (`npm run openapi:export`). Do not edit by hand.',
  '',
  `All paths are under \`/api/v1\`. ${count} endpoints. Interactive docs: \`/api/docs\` (when \`SWAGGER_ENABLED=true\`).`,
  '',
  'Access: 🔓 public · 👤 any logged-in user · 🛡 ADMIN or SUPER_ADMIN. Request fields: `*` = required.',
  '',
  'Errors always have the shape `{ statusCode, message, error, requestId }` (Bangla `message`); a meeting clash',
  '(409) adds `blocking`. Auth: Bearer access token (header) or the httpOnly `access_token` cookie.',
  '',
];
for (const tag of tags) {
  lines.push(`## ${tag}`, '', '| Method | Path | Access | Purpose | Main request fields | Responses |', '|---|---|---|---|---|---|', ...groups.get(tag)!, '');
}
writeFileSync(join(root, 'API.md'), `${lines.join('\n')}\n`);
console.log(`Wrote docs/API.md (${count} endpoints in ${tags.length} groups)`);
